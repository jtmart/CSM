<#
.SYNOPSIS
  Post-investigation finalizer, one run:

  1. Cleanup of leftovers that turned out irrelevant to the fix:
     - deletes the Clink drain lua (%LOCALAPPDATA%\clink\zz-flush-startup-input.lua)
       - there is no Clink on this setup, the hook was inert
     - strips the bash/zsh startup-input-drain blocks from the WSL rc files
       - the leak was psmux->pwsh, so they only added ~200ms to WSL first prompts
  2. Redeploys the final replication folder (embedded below, nothing to unzip):
       fix-terminal-startup.ps1, fix-psmux-drain.ps1, fix-terminal-startup.sh,
       install.ps1, README.md
     into C:\Users\jtm\Dropbox\Sync\add-templates\terminal-startup\
     (override with -Destination).

.EXAMPLE
  pwsh -ExecutionPolicy Bypass -File .\finalize-terminal-setup.ps1
#>
[CmdletBinding()]
param(
  [string]$Destination = 'C:\Users\jtm\Dropbox\Sync\add-templates\terminal-startup'
)
$ErrorActionPreference = 'Continue'

Write-Host "== cleanup: investigation leftovers ==" -ForegroundColor Cyan
$lua = Join-Path $env:LOCALAPPDATA 'clink\zz-flush-startup-input.lua'
if (Test-Path $lua) { Remove-Item $lua -Force; Write-Host "  removed $lua (no Clink on this machine; hook was inert)" }
else { Write-Host '  no Clink hook present' }

if (Get-Command wsl -ErrorAction SilentlyContinue) {
  $bashCleanup = @'
for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
  [ -f "$rc" ] || continue
  if grep -q "startup-input-drain" "$rc"; then
    cp "$rc" "$rc.bak-cleanup-$(date +%Y%m%d-%H%M%S)"
    sed -i '/^# --- startup-input-drain/,/^# --- end startup-input-drain ---$/d' "$rc"
    echo "  removed drain hook from $rc"
  else
    echo "  $rc - no drain hook"
  fi
done
'@
  wsl -e bash -c $bashCleanup
}
else { Write-Host '  no WSL - skipped rc cleanup' }

Write-Host "`n== deploy replication folder ==" -ForegroundColor Cyan
if (-not (Test-Path $Destination)) { New-Item -ItemType Directory -Path $Destination -Force | Out-Null }
