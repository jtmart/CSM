<#
.SYNOPSIS
  Cleanup for the fastfetch cached-splash experiment, one run, no follow-ups:

  1. PowerShell profiles: remove the cached-splash block and restore the
     original fastfetch line (the cache is generated by a non-tty fastfetch,
     which falls back to '?' placeholder glyphs and doubles up with any other
     fastfetch invocation in the startup chain). The cached oh-my-posh init is
     KEPT - it works and saves a process spawn per shell.
  2. WSL .bashrc/.zshrc (via wsl, if present): same revert there.
  3. Deletes the stale splash caches on both sides.
  4. Sets Clink's prompt.async to false - Clink renders prompts asynchronously
     by default, so oh-my-posh's prompt filter runs after input is live; any
     terminal query it triggers replies straight onto the input line ("7f7f\").
     Synchronous prompts close that window for a few ms of prompt latency.

  Idempotent. Requires PowerShell 7+.

.EXAMPLE
  pwsh -ExecutionPolicy Bypass -File .\revert-splash-cache.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

function Note([string]$Message) { Write-Host "  $Message" }

# --- 1. PowerShell profiles: undo the fastfetch splash cache ---------------

function Restore-Profile([string]$Path) {
  Write-Host "`n== $Path ==" -ForegroundColor Cyan
  if (-not (Test-Path $Path)) { Write-Host '  not present - skipped'; return }

  $lines = [System.Collections.Generic.List[string]](Get-Content $Path)
  $out = [System.Collections.Generic.List[string]]::new()
  $changed = $false
  $inBlock = $false
  foreach ($line in $lines) {
    if ($line -match '^# --- fastfetch cached splash \(speed-terminal-startup\) ---') { $inBlock = $true; $changed = $true; continue }
    if ($inBlock) {
      if ($line -match '^# --- end fastfetch cached splash ---') { $inBlock = $false }
      continue
    }
    if ($line -match '^# moved to cached splash below \(speed-terminal-startup\): (.+)$') {
      $out.Add($Matches[1])
      $changed = $true
      Note "restored: $($Matches[1])"
      continue
    }
    $out.Add($line)
  }
  # drop a trailing blank line left behind by the removed block
  while ($out.Count -gt 0 -and $out[$out.Count - 1] -eq '') { $out.RemoveAt($out.Count - 1) }

  if ($changed) {
    Set-Content -Path $Path -Value ($out -join [Environment]::NewLine) -Encoding utf8
    Note 'splash cache block removed'
  }
  else {
    Write-Host '  no splash cache block found - nothing to revert'
  }
}

$profiles = @($PROFILE.CurrentUserAllHosts, $PROFILE.CurrentUserCurrentHost) | Select-Object -Unique
foreach ($p in $profiles) { Restore-Profile $p }

$staleCache = Join-Path $env:LOCALAPPDATA 'ftsu-splash.txt'
if (Test-Path $staleCache) { Remove-Item $staleCache, "$staleCache.new" -Force -ErrorAction SilentlyContinue; Note "deleted $staleCache" }

# --- 2. WSL side -----------------------------------------------------------

Write-Host "`n== WSL ==" -ForegroundColor Cyan
if (Get-Command wsl -ErrorAction SilentlyContinue) {
  $bashRevert = @'
for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
  [ -f "$rc" ] || continue
  if grep -q "fastfetch cached splash (speed-terminal-startup)" "$rc"; then
    cp "$rc" "$rc.bak-revert-$(date +%Y%m%d-%H%M%S)"
    sed -i '\|^# --- fastfetch cached splash (speed-terminal-startup) ---$|,\|^# --- end fastfetch cached splash ---$|d' "$rc"
    sed -i 's|^# moved to cached splash below (speed-terminal-startup): ||' "$rc"
    echo "  reverted splash cache in $rc"
  else
    echo "  $rc - no splash cache block"
  fi
done
rm -f "$HOME/.cache/ftsu-splash" "$HOME/.cache/ftsu-splash.new" && echo "  cleared ~/.cache/ftsu-splash"
'@
  wsl -e bash -c $bashRevert
}
else {
  Write-Host '  no WSL detected - skipped'
}

# --- 3. Clink: synchronous prompt ------------------------------------------

Write-Host "`n== Clink ==" -ForegroundColor Cyan
$clink = Get-Command clink -ErrorAction SilentlyContinue
if (-not $clink) {
  foreach ($cand in @("$env:LOCALAPPDATA\clink\clink_x64.exe",
      "$env:ProgramFiles\clink\clink_x64.exe",
      "${env:ProgramFiles(x86)}\clink\clink_x64.exe")) {
    if (Test-Path $cand) { $clink = $cand; break }
  }
}
if ($clink) {
  & $clink set prompt.async false | Out-Host
  Note 'prompt.async set to false (prompt filters can no longer race the input line)'
}
else {
  Write-Host '  clink not found on PATH - run this once in a cmd tab instead:'
  Write-Host '    clink set prompt.async false'
}

Write-Host "`nDone. Open a new tab of each kind - single splash with proper icons, and" -ForegroundColor Green
Write-Host 'check whether the cmd-tab stray characters are finally gone.' -ForegroundColor Green
